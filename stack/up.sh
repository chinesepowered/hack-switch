#!/usr/bin/env bash
# Boot a local Switch server for CapyTales: Postgres, switch-core, the gateway
# (admin dashboard) and Mattermost (the family's chat app), all in Docker.
#
#   ./stack/up.sh          start (generates stack/.env with fresh secrets once)
#   ./stack/down.sh        stop, keeping data
#
# Pinned to a Switch release so the compose file and the images always match.
set -euo pipefail

SWITCH_VERSION="${SWITCH_VERSION:-0.31.0}"
HERE="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$HERE/.env"
COMPOSE_FILE="$HERE/switch-compose.yml"
RAW="https://raw.githubusercontent.com/sandbox-quantum/switch/switch-v${SWITCH_VERSION}"

command -v docker >/dev/null || { echo "Docker is required." >&2; exit 1; }
command -v openssl >/dev/null || { echo "openssl is required." >&2; exit 1; }

if [ ! -f "$COMPOSE_FILE" ]; then
  echo "Fetching Switch ${SWITCH_VERSION} compose file..."
  curl -fsSL "$RAW/deploy/local/standalone-docker-compose.yml" -o "$COMPOSE_FILE"
fi

rand() { openssl rand -hex 24; }

if [ ! -f "$ENV_FILE" ]; then
  echo "Writing $ENV_FILE with fresh secrets..."
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by stack/up.sh. Holds secrets: never commit it.
SWITCH_REGISTRY=ghcr.io
SWITCH_IMAGE_NAMESPACE=sandbox-quantum
SWITCH_VERSION=${SWITCH_VERSION}
SWITCH_BIND_ADDR=127.0.0.1
GATEWAY_HOST_PORT=3000
API_HOST_PORT=8000
MATTERMOST_HOST_PORT=8065
POSTGRES_HOST_PORT=5432

DB_HOST=postgres
DB_PORT=5432
DB_USER=switch_app
DB_PASSWORD=$(rand)
DB_OWNER_USER=postgres
DB_OWNER_PASSWORD=$(rand)
DB_NAME=switch
MATRIX_SERVER_NAME=localhost

AGENT_REGISTRATION_TOKEN=$(rand)
JWT_SECRET_KEY=$(rand)
SECRET_KEYS=capytales:$(openssl rand -hex 32)
# Agent management lets the headless agent controller run our capybaras.
FEATURE_FLAGS_ENABLED=agent_management
CONTROLLER_TOKEN_SECRET=$(openssl rand -base64 48 | tr -d '\n=+/')

GATEWAY_ADMIN_EMAIL=admin@switch.local
GATEWAY_ADMIN_PASSWORD=$(rand)
FRONTEND_BASE_URL=http://localhost:3000
GATEWAY_COOKIE_SECURE=false
GATEWAY_PUBLIC_URL=http://localhost:8000
TELEMETRY_ENABLED=false

MATTERMOST_ADMIN_USER=admin
MATTERMOST_ADMIN_PASSWORD=$(rand)
MATTERMOST_TEAM_NAME=capytales
MATTERMOST_USER=parent
MATTERMOST_USER_PASSWORD=$(rand)
EOF
fi

# Docker Hub rate-limits anonymous pulls from shared IPs. If a pull fails,
# fetch the same image from a public mirror and tag it with the expected name.
pull_with_fallback() {
  local image="$1" mirror="$2"
  docker image inspect "$image" >/dev/null 2>&1 && return 0
  docker pull -q "$image" >/dev/null 2>&1 && return 0
  echo "Docker Hub refused $image; trying $mirror"
  local ref="$mirror"
  if [[ "$mirror" == mirror.gcr.io/* ]]; then
    local digest
    digest=$(docker manifest inspect "$mirror" | python3 -c 'import sys,json; m=json.load(sys.stdin); print(next(x["digest"] for x in m["manifests"] if x["platform"]["os"]=="linux" and x["platform"]["architecture"]=="amd64"))')
    ref="${mirror%%:*}@${digest}"
  fi
  docker pull -q "$ref" >/dev/null
  docker tag "$ref" "$image"
}
pull_with_fallback postgres:16-alpine public.ecr.aws/docker/library/postgres:16-alpine
pull_with_fallback mattermost/mattermost-team-edition:11.9.0 mirror.gcr.io/mattermost/mattermost-team-edition:11.9.0

docker compose -f "$COMPOSE_FILE" --env-file "$ENV_FILE" --project-name capytales \
  --profile collab --profile gateway up -d

echo "Waiting for switch-core..."
for _ in $(seq 1 90); do
  curl -fsS http://127.0.0.1:8000/health >/dev/null 2>&1 && break
  sleep 2
done
curl -fsS http://127.0.0.1:8000/health >/dev/null && echo "switch-core is up on :8000"
echo "Mattermost: http://localhost:8065   Gateway: http://localhost:3000"
